import sys, copy
from docx import Document
from docx.shared import Pt, RGBColor, Cm
from docx.oxml.ns import qn
from docx.oxml import OxmlElement
from docx.enum.table import WD_TABLE_ALIGNMENT
src,dst=sys.argv[1],sys.argv[2]
tocf=sys.argv[3] if len(sys.argv)>3 else None
d=Document(src)
NAVY='1F3864'
def set_cell_shading(cell,fill):
    tcPr=cell._tc.get_or_add_tcPr()
    for e in tcPr.findall(qn('w:shd')): tcPr.remove(e)
    shd=OxmlElement('w:shd'); shd.set(qn('w:val'),'clear'); shd.set(qn('w:color'),'auto'); shd.set(qn('w:fill'),fill); tcPr.append(shd)
def borders(tbl):
    tblPr=tbl._tbl.tblPr
    for e in tblPr.findall(qn('w:tblBorders')): tblPr.remove(e)
    b=OxmlElement('w:tblBorders')
    for side,sz,col in (('top',10,NAVY),('bottom',10,NAVY),('insideH',4,'B8C4D2'),('left',0,'FFFFFF'),('right',0,'FFFFFF'),('insideV',4,'DCE3EA')):
        e=OxmlElement(f'w:{side}'); e.set(qn('w:val'),'single' if sz else 'nil'); e.set(qn('w:sz'),str(sz)); e.set(qn('w:space'),'0'); e.set(qn('w:color'),col); b.append(e)
    tblPr.append(b)
    for e in tblPr.findall(qn('w:tblCellMar')): tblPr.remove(e)
    m=OxmlElement('w:tblCellMar')
    for side,v in (('top',40),('bottom',40),('left',80),('right',80)):
        e=OxmlElement(f'w:{side}'); e.set(qn('w:w'),str(v)); e.set(qn('w:type'),'dxa'); m.append(e)
    tblPr.append(m)
    for e in tblPr.findall(qn('w:jc')): tblPr.remove(e)
    jc=OxmlElement('w:jc'); jc.set(qn('w:val'),'center'); tblPr.append(jc)
for tbl in d.tables:
    borders(tbl)
    for i,row in enumerate(tbl.rows):
        # header row repeat
        if i==0:
            trPr=row._tr.get_or_add_trPr(); h=OxmlElement('w:tblHeader'); h.set(qn('w:val'),'true'); trPr.append(h)
        cant=OxmlElement('w:cantSplit'); row._tr.get_or_add_trPr().append(cant)
        for cell in row.cells:
            if i==0: set_cell_shading(cell,NAVY)
            elif i%2==0: set_cell_shading(cell,'F2F6FA')
            for p in cell.paragraphs:
                p.paragraph_format.space_after=Pt(1); p.paragraph_format.space_before=Pt(1)
                for r in p.runs:
                    r.font.size=Pt(9.5)
                    if i==0: r.font.bold=True; r.font.color.rgb=RGBColor(0xFF,0xFF,0xFF)
# keep figures with their captions
body=d.element.body
for p in d.paragraphs:
    if p.style.name in ('Captioned Figure','Figure'):
        p.paragraph_format.keep_with_next=True
# cached table of contents (Word refreshes it on open because of updateFields)
import json
if tocf:
    toc=json.load(open(tocf))
    W='{http://schemas.openxmlformats.org/wordprocessingml/2006/main}'
    for p in d.paragraphs:
        if 'The table of contents is generated by Word' in p.text:
            ph=p._p; break
    runs=ph.findall(W+'r')
    # runs: begin, instr, separate, text, end
    begin,instr,sep,txt,end=runs
    parent=ph.getparent(); idx=parent.index(ph)
    newps=[]
    for i,(lvl,text,page) in enumerate(toc):
        P=OxmlElement('w:p'); pPr=OxmlElement('w:pPr'); ps=OxmlElement('w:pStyle'); ps.set(qn('w:val'),'TOC%d'%lvl); pPr.append(ps)
        tabs=OxmlElement('w:tabs'); tb=OxmlElement('w:tab'); tb.set(qn('w:val'),'right'); tb.set(qn('w:leader'),'dot'); tb.set(qn('w:pos'),'9350'); tabs.append(tb); pPr.append(tabs)
        sp=OxmlElement('w:spacing'); sp.set(qn('w:before'),'60' if lvl==1 else '0'); sp.set(qn('w:after'),'0'); sp.set(qn('w:line'),'250'); sp.set(qn('w:lineRule'),'auto'); pPr.append(sp)
        ind=OxmlElement('w:ind'); ind.set(qn('w:left'),'0' if lvl==1 else '440'); pPr.append(ind)
        P.append(pPr)
        if i==0:
            for r in (begin,instr,sep): P.append(copy.deepcopy(r))
        def run(t,bold=False):
            R=OxmlElement('w:r'); rPr=OxmlElement('w:rPr')
            sz=OxmlElement('w:sz'); sz.set(qn('w:val'),'21' if lvl==1 else '20'); rPr.append(sz)
            if bold: rPr.append(OxmlElement('w:b'))
            col=OxmlElement('w:color'); col.set(qn('w:val'),'1F3864' if lvl==1 else '333333'); rPr.append(col)
            R.append(rPr); T=OxmlElement('w:t'); T.set(qn('xml:space'),'preserve'); T.text=t; R.append(T); return R
        num,_,title=text.partition('	')
        label=(num+'   '+title) if title else text
        P.append(run(label,lvl==1))
        R=OxmlElement('w:r'); R.append(OxmlElement('w:tab')); P.append(R)
        P.append(run(str(page),lvl==1))
        if i==len(toc)-1: P.append(copy.deepcopy(end))
        newps.append(P)
    parent.remove(ph)
    for k,P in enumerate(newps): parent.insert(idx+k,P)
# updateFields so Word fills the TOC on open
st=d.settings.element
u=OxmlElement('w:updateFields'); u.set(qn('w:val'),'true'); st.append(u)
d.core_properties.title='AI-Assisted Reverse Engineering of an Industrial Axial-Flow Compressor — Project Proposal'
d.core_properties.author='Alireza Bayati; Melika Bali'
d.core_properties.subject='Turbomachinery course project, Amirkabir University of Technology'
d.core_properties.keywords='axial compressor; turbomachinery; reverse engineering; AI; MGT-70'
d.core_properties.comments='Prepared with the assistance of Claude (Anthropic).'
d.save(dst)
print('tables',len(d.tables))
